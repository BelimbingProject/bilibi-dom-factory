-- Core owns the product's identity (code, name, unit). Factory keeps only its
-- manufacturing facts, keyed by the Core product ID, which is an opaque
-- reference validated through Core's facade. Disposable databases need no
-- backfill, so the tables that held the copied code and name are replaced.
DROP TABLE factory_formula_revisions;
DROP TABLE factory_routing_revisions;
DROP TABLE factory_products;
CREATE TABLE factory_product_definitions (
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 product_id bigint NOT NULL CHECK(product_id > 0),
 item_id bigint NOT NULL CHECK(item_id > 0),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(tenant_id,company_id,product_id),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 CONSTRAINT factory_product_definitions_company_item_unique UNIQUE(company_id,item_id)
);
CREATE TABLE factory_formula_revisions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 product_id bigint NOT NULL,
 version integer NOT NULL CHECK(version > 0),
 lines jsonb NOT NULL CHECK(jsonb_typeof(lines)='array' AND jsonb_array_length(lines)>0),
 process_config jsonb NOT NULL CHECK(jsonb_typeof(process_config)='object'),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(tenant_id,company_id,product_id) REFERENCES factory_product_definitions(tenant_id,company_id,product_id) ON DELETE RESTRICT,
 CONSTRAINT factory_formula_revisions_product_version_unique UNIQUE(company_id,product_id,version)
);
CREATE TABLE factory_routing_revisions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id bigint NOT NULL,
 company_id bigint NOT NULL,
 product_id bigint NOT NULL,
 version integer NOT NULL CHECK(version > 0),
 operations jsonb NOT NULL CHECK(jsonb_typeof(operations)='array' AND jsonb_array_length(operations)>0),
 process_config jsonb NOT NULL CHECK(jsonb_typeof(process_config)='object'),
 inserted_at timestamptz NOT NULL DEFAULT now(),
 FOREIGN KEY(tenant_id,company_id) REFERENCES companies(tenant_id,id) ON DELETE RESTRICT,
 FOREIGN KEY(tenant_id,company_id,product_id) REFERENCES factory_product_definitions(tenant_id,company_id,product_id) ON DELETE RESTRICT,
 CONSTRAINT factory_routing_revisions_product_version_unique UNIQUE(company_id,product_id,version)
);
CREATE TRIGGER factory_formula_revisions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_formula_revisions FOR EACH STATEMENT EXECUTE FUNCTION factory_product_definition_immutable();
CREATE TRIGGER factory_routing_revisions_immutable BEFORE UPDATE OR DELETE OR TRUNCATE
 ON factory_routing_revisions FOR EACH STATEMENT EXECUTE FUNCTION factory_product_definition_immutable();
